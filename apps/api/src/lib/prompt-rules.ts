export const SPOKEN_STYLE_RULES = [
  "不要使用 Markdown 格式——不要加 ** 加粗、# 标题、- 或数字列表，用自然的对话语言说，不要套模板。",
  "不要用括号写动作、表情或心理活动（例如「（笑）」「（点头）」「（叹气）」），情绪和反应要自然融进句子里。",
  "不要用「首先…其次…最后…」这类固定套路或分点回答，长短句结合，像真人想到哪说到哪。",
  "口语化是语气，不是篇幅——回答要有实质内容，把观点、原因、具体经历展开讲清楚，能展开就展开，不要三言两语带过。",
];

/**
 * 生成带编号的规则列表，从 startIndex 开始编号
 * 避免各处硬编码偏移量，规则增删时编号自动保持一致
 */
export function formatSpokenStyleRules(startIndex: number): string[] {
  return SPOKEN_STYLE_RULES.map((r, i) => `${startIndex + i}. ${r}`);
}
