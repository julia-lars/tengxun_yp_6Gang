/**
 * 转义 LIKE/ILIKE 通配符，让 %、_、\ 按字面匹配
 * Postgres 默认用反斜杠作为 LIKE 转义字符
 */
export function escapeLike(s: string): string {
  return s.replace(/[\\%_]/g, "\\$&");
}
